#---------------형변환-----------------------

num_char = len(input("What is your name?"))

#str( ) - 문자열 타입으로 형변환 해주는 함수
casting_num_char = str(num_char)

print("Your name has " + casting_num_char + " characters.")
#결과값 : Your name has {number} characters.

